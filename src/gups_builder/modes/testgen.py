"""The generated builder_test.star, rewritten in full on every write.

One function per room with at least one testable exit: a testable exit has a
standard direction, no door or an open one, and a target in the package. Each
exit after the first spawns a fresh player in the room rather than walking
back, so a one-way exit or a door on the far side never breaks the test.

One function per plain mob with declared vitals: it spawns the mob in a room
of the package and checks its maximum vitals.

Code can veto or redirect a move, and the builder cannot tell what it does, so
a room with any field computed by code, or one that spawns a mob that has such
a field (or is not a plain mob of this package), is left to the package's own
tests, and so is every exit into a room with code or one the reader could not
hold as a plain declaration. A mob with a field computed by code is left to
the package's own tests too.
"""

from __future__ import annotations

from gups_builder.engine.world import WorldDescription
from gups_builder.grid.derive import DIRECTION_DELTAS
from gups_builder.star.reader import DeclView, PackageView
from gups_builder.star.values import Value, is_editable

_HEADER = (
    "# Generated by gups-builder from this package's rooms and mobs; "
    "it is rewritten on every write.\n"
    "# Put your own tests in another *_test.star file.\n"
)


def _direction(value: Value) -> str | None:
    """The exit's direction name, whatever it is called."""
    if isinstance(value, dict):
        const = value.get("$const")
        if isinstance(const, str) and const.startswith("DIR."):
            return const[4:]
        return None
    if isinstance(value, str):
        return value
    return None


def _door_state(value: Value) -> str | None:
    if not isinstance(value, dict) or value.get("$call") != "door":
        return None
    kwargs = value.get("kwargs")
    if not isinstance(kwargs, dict):
        return None
    state = kwargs.get("state")
    if isinstance(state, dict):
        const = state.get("$const")
        if isinstance(const, str) and const.startswith("DOOR."):
            return const[5:]
    return None


def _has_code(decl: DeclView) -> bool:
    return not all(is_editable(value) for value in decl.args.values())


def _plain_mob(view: PackageView, label: Value) -> bool:
    """True when the spawned mob is a plain mob of this package with no code."""
    if not isinstance(label, str):
        return False
    if label.startswith(":"):
        mob_id = label[1:]
    elif label.startswith(f"//{view.path}:"):
        mob_id = label.rsplit(":", 1)[1]
    else:
        return False
    mob = view.get("mob", mob_id)
    return mob is not None and not _has_code(mob)


def _without_code(decl: DeclView, view: PackageView) -> bool:
    if _has_code(decl):
        return False
    spawns = decl.args.get("spawns", [])
    if not isinstance(spawns, list):
        return False
    for spawn in spawns:
        if not isinstance(spawn, dict) or spawn.get("$call") != "spawn":
            return False
        args = spawn.get("args")
        if not isinstance(args, list) or not args or not _plain_mob(view, args[0]):
            return False
    return True


def _testable_exits(decl: DeclView, package: str) -> list[tuple[str, str]]:
    exits = decl.args.get("exits")
    if not isinstance(exits, list):
        return []
    out: list[tuple[str, str]] = []
    for item in exits:
        if not isinstance(item, dict) or item.get("$call") != "exit":
            continue
        args = item.get("args")
        if not isinstance(args, list) or not args:
            continue
        direction = _direction(args[0])
        if direction not in DIRECTION_DELTAS:
            continue
        kwargs = item.get("kwargs")
        if not isinstance(kwargs, dict):
            continue
        to = kwargs.get("to")
        if not isinstance(to, str):
            continue
        if not (to.startswith(":") or to.startswith(f"//{package}:")):
            continue
        target = to[1:] if to.startswith(":") else to.rsplit(":", 1)[1]
        state = _door_state(kwargs.get("door"))
        if state is not None and state != "open":
            continue
        out.append((direction, target))
    return out


def _declared_vitals(decl: DeclView) -> list[tuple[str, int]]:
    """The vitals the mob declares, in the order the file writes them."""
    value = decl.args.get("vitals")
    if not isinstance(value, dict) or value.get("$call") != "vitals":
        return []
    kwargs = value.get("kwargs")
    if not isinstance(kwargs, dict):
        return []
    return [(name, count) for name, count in kwargs.items() if isinstance(count, int)]


def _spawn_room(view: PackageView, rooms: list[DeclView], mob_id: str) -> str:
    """The first room whose spawns name the mob, else the package's first room."""
    for room in rooms:
        spawns = room.args.get("spawns")
        if not isinstance(spawns, list):
            continue
        for spawn in spawns:
            if not isinstance(spawn, dict) or spawn.get("$call") != "spawn":
                continue
            args = spawn.get("args")
            if not isinstance(args, list) or not args or not isinstance(args[0], str):
                continue
            if args[0] == f":{mob_id}" or args[0] == f"//{view.path}:{mob_id}":
                return room.id
    return rooms[0].id


def builder_test(package: str, world: WorldDescription, view: PackageView) -> str:
    """The test file for a zone package; empty when the package is not a zone."""
    for info in world.packages:
        if info.path == package and info.kind is not None and info.kind != "zone":
            return ""
    coded_rooms = {d.id for d in view.decls if d.kind == "room" and _has_code(d)}
    coded_rooms |= {o.id for o in view.opaque if o.kind == "room" and o.id is not None}
    lines = [_HEADER, "def test_builder_package_loads(t):", "    t.world(seed = 1)", ""]
    for decl in view.decls:
        if decl.kind != "room":
            continue
        if not _without_code(decl, view):
            continue
        exits = [
            (direction, to)
            for direction, to in _testable_exits(decl, view.path)
            if to not in coded_rooms
        ]
        if not exits:
            continue
        lines.append(f"def test_builder_{decl.id}_exits(t):")
        lines.append("    w = t.world(seed = 1)")
        for i, (direction, to) in enumerate(exits):
            name = "Walker" if i == 0 else f"Walker{i + 1}"
            lines.append(f'    p = w.spawn_player("{name}", at = ":{decl.id}")')
            lines.append(f'    p.do("{direction}")')
            lines.append(f'    t.eq(p.room, ":{to}")')
        lines.append("")
    rooms = [d for d in view.decls if d.kind == "room"]
    if rooms:
        for decl in view.decls:
            if decl.kind != "mob" or _has_code(decl):
                continue
            vitals = _declared_vitals(decl)
            if not vitals:
                continue
            lines.append(f"def test_builder_{decl.id}_vitals(t):")
            lines.append("    w = t.world(seed = 1)")
            lines.append(
                f'    m = w.spawn(":{decl.id}", at = ":{_spawn_room(view, rooms, decl.id)}")'
            )
            for vital, count in vitals:
                lines.append(f"    t.eq(m.max_{vital}, {count})")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
