def _decl(kind: str, rid: str, args: dict[str, Value], line: int) -> DeclView:
    return DeclView(
        kind=kind, id=rid, file=f"{kind}s.star", line=line, args=args, extra_positional=[]
    )


def _block(rid: str, direction: str, to: str) -> str:
    return (
        f"\ndef test_builder_{rid}_exits(t):\n"
        "    w = t.world(seed = 1)\n"
        f'    p = w.spawn_player("Walker", at = ":{rid}")\n'
        f'    p.do("{direction}")\n'
        f'    t.eq(p.room, ":{to}")\n'
    )


def test_rooms_with_code_are_left_to_their_own_tests() -> None:
    # Code may veto or redirect a move, so the builder cannot know where the
    # exit leads: a hook on the room, a hook on the target, or a mob with code.
    hook: Value = {"$ref": "_hall_enter"}
    rooms = [
        _decl("room", "hooked", {"exits": [_exit(_dir("north"), ":plain")], "on_exit": hook}, 1),
        _decl("room", "plain", {"exits": [_exit(_dir("east"), ":target_hooked")]}, 2),
        _decl("room", "target_hooked", {"exits": [], "on_enter": hook}, 3),
        _decl(
            "room",
            "guarded",
            {
                "exits": [_exit(_dir("south"), ":plain")],
                "spawns": [{"$call": "spawn", "args": [":guide"], "kwargs": {}}],
            },
            4,
        ),
        _decl(
            "room",
            "visited",
            {
                "exits": [_exit(_dir("west"), ":plain")],
                "spawns": [{"$call": "spawn", "args": [":rat"], "kwargs": {"count": 2}}],
            },
            5,
        ),
        _decl(
            "room",
            "foreign",
            {
                "exits": [_exit(_dir("up"), ":plain")],
                "spawns": [{"$call": "spawn", "args": ["//other:wolf"], "kwargs": {}}],
            },
            6,
        ),
        _decl("mob", "guide", {"name": "the guide", "before_exit": {"$ref": "_blocks"}}, 1),
        _decl("mob", "rat", {"name": "a rat"}, 2),
    ]
    view = PackageView(path="zones/mansion", files={}, decls=rooms, opaque=[])
    assert builder_test("zones/mansion", _world("zones/mansion", "zone"), view) == (
        _header() + _block("visited", "west", "plain")
    )
